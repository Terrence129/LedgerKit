import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const repositoryRoot = resolve(import.meta.dirname, "..");
const appRoot = join(repositoryRoot, "app");
const releaseRoot = join(repositoryRoot, "docs/release");
mkdirSync(releaseRoot, { recursive: true });

const packageLock = JSON.parse(readFileSync(join(appRoot, "package-lock.json"), "utf8"));
const releaseVersion = packageLock.version;
const npmComponents = Object.entries(packageLock.packages)
  .filter(([path, value]) => path.startsWith("node_modules/") && value.dev !== true)
  .map(([path, value]) => {
    const name = path.slice("node_modules/".length);
    const packageJson = JSON.parse(readFileSync(join(appRoot, path, "package.json"), "utf8"));
    return {
      type: "library",
      group: name.startsWith("@") ? name.split("/")[0] : undefined,
      name,
      version: value.version,
      licenses: packageJson.license ? [{ license: { name: packageJson.license } }] : undefined,
      purl: `pkg:npm/${encodeURIComponent(name)}@${value.version}`,
      scope: "required",
    };
  });

const metadata = JSON.parse(execFileSync("cargo", ["metadata", "--locked", "--format-version", "1", "--manifest-path", join(appRoot, "src-tauri/Cargo.toml")], { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 }));
const rootId = metadata.resolve.root;
const nodeMap = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
const packageMap = new Map(metadata.packages.map((item) => [item.id, item]));
const included = new Set();
const queue = [rootId];
while (queue.length) {
  const id = queue.shift();
  if (included.has(id)) continue;
  included.add(id);
  const node = nodeMap.get(id);
  for (const dependency of node?.deps ?? []) {
    if (dependency.dep_kinds.some((kind) => kind.kind === null)) queue.push(dependency.pkg);
  }
}
included.delete(rootId);
const cargoComponents = [...included].map((id) => packageMap.get(id)).filter(Boolean).map((item) => ({
  type: "library",
  name: item.name,
  version: item.version,
  licenses: item.license ? [{ license: { name: item.license } }] : undefined,
  purl: `pkg:cargo/${encodeURIComponent(item.name)}@${item.version}`,
  scope: "required",
}));

const components = [...npmComponents, ...cargoComponents]
  .map((component) => Object.fromEntries(Object.entries(component).filter(([, value]) => value !== undefined)))
  .sort((left, right) => left.purl.localeCompare(right.purl));
const sbom = {
  bomFormat: "CycloneDX",
  specVersion: "1.5",
  version: 1,
  metadata: { component: { type: "application", name: "LedgerKit", version: releaseVersion } },
  components,
};
writeFileSync(join(releaseRoot, "sbom.cdx.json"), `${JSON.stringify(sbom, null, 2)}\n`);

const rows = components.map((item) => `| \`${item.purl}\` | ${item.licenses?.[0]?.license?.name ?? "NOASSERTION"} | Runtime dependency |`);
const licenses = `# LedgerKit ${releaseVersion} license inventory

Generated by \`node tools/generate-release-evidence.mjs\` from the locked npm and Cargo runtime dependency graphs. \`NOASSERTION\` means the package metadata did not declare a machine-readable license and requires manual source review before a public binary release.

| Package | Declared license | Scope |
|---|---|---|
${rows.join("\n")}
`;
writeFileSync(join(releaseRoot, "licenses.md"), licenses);
console.log(`RELEASE_EVIDENCE=PASS components=${components.length}`);
